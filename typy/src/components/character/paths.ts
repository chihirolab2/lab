type P = [number, number];

/**
 * 前髪パスを生成する。top はつむじ〜こめかみのドーム、edge は右こめかみ→左こめかみへ
 * 「谷(valley)→毛先(tip)」を交互に並べた点列。sweep で毛束の流れ（左右）を付ける。
 */
function fringePath(edgeIn: P[], sweep: number, dome: P = [120, 24]): string {
  // 頭の丸みに合わせて横方向にボリュームを出す
  const edge: P[] = edgeIn.map(([x, y], i) => {
    const end = i === 0 || i === edgeIn.length - 1;
    const push = i === 0 ? 3 : end ? -3 : 0;
    return [Math.round((120 + (x - 120) * 1.07 + push) * 10) / 10, end ? y + 12 : y];
  });
  const [first] = edge;
  const last = edge[edge.length - 1];
  let d = `M${last[0]},${last[1]} C${last[0] - 14},${last[1] - 66} ${dome[0] - 44},${dome[1]} ${dome[0]},${dome[1]} `;
  d += `C${dome[0] + 44},${dome[1]} ${first[0] + 14},${first[1] - 66} ${first[0]},${first[1]} `;
  for (let i = 1; i < edge.length; i++) {
    const [ax, ay] = edge[i - 1];
    const [bx, by] = edge[i];
    const goingDown = by > ay;
    if (goingDown) {
      // 谷 → 毛先：ふくらみを持たせて流れる毛束に
      const cx = ax + (bx - ax) * 0.25 + sweep;
      const cy = ay + (by - ay) * 0.75;
      d += `Q${cx},${cy} ${bx},${by} `;
    } else {
      // 毛先 → 谷：鋭く切れ込む
      const cx = ax + (bx - ax) * 0.7 + sweep * 0.25;
      const cy = ay - (ay - by) * 0.35;
      d += `Q${cx},${cy} ${bx},${by} `;
    }
  }
  return d + 'Z';
}

/** 前髪の毛束ライン（質感用）。毛先に向かって流れる細い線 */
function strandLines(edgeIn: P[], sweep: number): string {
  let d = '';
  for (let i = 2; i < edgeIn.length - 2; i += 2) {
    const [tx, ty] = edgeIn[i];
    const x = 120 + (tx - 120) * 1.07;
    const sx = 120 + (x - 120) * 0.55;
    d += `M${sx},${44} Q${x + sweep * 1.5},${ty - 30} ${x - sweep * 0.6},${ty - 10} `;
  }
  return d;
}

